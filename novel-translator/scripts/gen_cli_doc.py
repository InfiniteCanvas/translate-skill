"""Regenerate `references/cli.md` from `translate.py`'s argparse tree.

    uv run scripts/gen_cli_doc.py            # rewrite the file
    uv run scripts/gen_cli_doc.py --check    # print a diff summary, change nothing

The command inventory -- which subcommands exist, which flags each takes, their
metavars, choices, defaults and requiredness, the shared `parents=[...]` options
every command inherits, and each command's own usage line -- is read off the
live parser, never written out by hand. A hand-written list rots the moment a
subcommand is added, which is how the command surface in this skill had already
drifted three times; `tests/test_cli_doc.py` regenerates this file in memory and
fails when the committed bytes differ, so the drift cannot land again.

`EXIT_CODES` is the one hand-maintained table: no exit code is derivable from an
argparse tree. It restates the contract `translate.main()` implements, and
`references/file-formats.md` section "Exit codes" remains the normative
per-command matrix. Editing the doc by hand is therefore never the fix --
regenerate it, and change the code it describes.

The output is byte-stable: command and option order follow the parser's own
insertion order, wrapping uses a fixed width rather than the terminal's, and the
file is written with LF endings (see the repo's .gitattributes), so the
comparison in the test is a plain byte compare on every platform.
"""

from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

SCRIPT_DIR = Path(__file__).resolve().parent
if str(SCRIPT_DIR) not in sys.path:
    sys.path.insert(0, str(SCRIPT_DIR))

import translate

DOC_PATH = SCRIPT_DIR.parent / "references" / "cli.md"

PROSE_WIDTH = 88
USAGE_WIDTH = 100

EXIT_CODES: tuple[tuple[int, str, str], ...] = (
    (0, "success, including a run that had nothing to do", "every command"),
    (1, "the command ran and its answer is negative: a chapter ended "
        "`needs-review`, epubcheck reported validation errors, a review report "
        "was refused as stale, a term sits below its significance floor, a "
        "search matched nothing, or a check confirmed a problem. Which commands "
        "can exit 1 is enumerated per command in `references/file-formats.md` "
        "section \"Exit codes\".",
     "per command"),
    (2, "usage or setup error -- bad arguments, a missing or corrupt project "
        "file, a provider array that resolves no endpoint. One `[FAIL]` line, "
        "never a traceback. Also `build-epub` when the builder subprocess "
        "itself crashes, and `ping` when a provider is unreachable.",
     "every command"),
    (3, "a provider call failed after exhausting its retries and the run "
        "stopped. No surviving candidate is substituted and no partial chapter "
        "is written; `references/file-formats.md` section \"Provider failure is "
        "fatal\" has the full ladder.",
     "every command"),
    (130, "interrupted at the keyboard (`Ctrl-C`) -- chapter state is saved, "
          "so re-running the same command resumes", "every command"),
)

_HEADER = """\
# CLI reference

Generated from `scripts/translate.py`'s argparse tree by
`scripts/gen_cli_doc.py` -- **do not edit this file by hand**:

```bash
uv run scripts/gen_cli_doc.py            # rewrite it from the parser
uv run scripts/gen_cli_doc.py --check    # fail if it is stale, write nothing
```

`tests/test_cli_doc.py` regenerates this file in memory and compares the bytes,
so a subcommand or flag that lands without regenerating fails the gate.

This is the single source for **which commands exist and what they accept**.
`SKILL.md`, `README.md` and `references/maintenance.md` describe what each
command *does* and point here for the surface itself.
"""

_INVOCATION = """\
## Invocation

```bash
uv run scripts/translate.py <command> [--project <dir>] [options]
uv run scripts/translate.py <command> <action> [--project <dir>] [options]
```

`--project` defaults to the current directory and is accepted before the
subcommand, after it, and (for the nested actions) after the action, so all
three of these name the same project:

```bash
uv run scripts/translate.py --project <dir> status
uv run scripts/translate.py status --project <dir>
uv run scripts/translate.py glossary count --project <dir> <term>
```

The placeholder after a flag is argparse's own: the `metavar` when the command
sets one, otherwise the argument's internal destination name. That is why the
same `--project` flag reads `--project PROJECT` on a top-level command and
`--project PROJECT_ACTION` on a nested one -- the placeholder differs, the flag
does not, and both resolve the same directory.
"""


def _collapse(text: str) -> str:
    """One line, single spaces -- argparse help strings are pre-wrapped."""
    return re.sub(r"\s+", " ", text or "").strip()


def _cell(text: str) -> str:
    """A markdown table cell: one line, pipes escaped."""
    return _collapse(text).replace("|", "\\|")


def _wrap(text: str, width: int, first: str = "", rest: str = "") -> list[str]:
    """Greedy word wrap on a fixed width. The terminal's width is never read,
    so the same input always renders the same bytes."""
    words = text.split()
    if not words:
        return [first.rstrip()]
    lines: list[str] = []
    cur = first
    for word in words:
        trial = f"{cur} {word}" if cur.strip() else cur + word
        if cur.strip() and len(trial) > width:
            lines.append(cur)
            cur = rest + word
        else:
            cur = trial
    lines.append(cur)
    return lines


def _paragraph(text: str, indent: str = "") -> list[str]:
    return _wrap(_collapse(text), PROSE_WIDTH, indent, indent)


def _placeholder(action: argparse.Action) -> str:
    """argparse's own value placeholder: metavar, else the choices, else the
    dest uppercased -- the same fallback chain argparse's usage formatter uses."""
    if action.metavar:
        return action.metavar
    if action.choices:
        return "{" + ",".join(str(c) for c in action.choices) + "}"
    if action.nargs == 0:
        return ""
    return action.dest.upper()


def _label(action: argparse.Action) -> str:
    """`--source TERM`, `term TERM`, `--list`, `[spec]`, `action` -- one row's
    argument. A subparsers action's dest and metavar are both the same word, so
    it is emitted once rather than as `action action`."""
    if isinstance(action, argparse._SubParsersAction):
        return action.metavar or action.dest
    placeholder = _placeholder(action)
    if action.option_strings:
        flag = action.option_strings[0]
    elif action.nargs == "?":
        return f"[{action.dest}]"
    else:
        flag = action.dest
    return f"{flag} {placeholder}".strip()


def _is_flag(action: argparse.Action) -> bool:
    return action.nargs == 0 or isinstance(
        action, (argparse._StoreTrueAction, argparse._StoreFalseAction,
                 argparse._CountAction, argparse._HelpAction))


def _default(action: argparse.Action) -> str:
    """The rendered default, or `(required)` -- argparse's SUPPRESS default is
    how a help action hides, and never reaches a table row."""
    if action.default is argparse.SUPPRESS:
        return "(hidden)"
    if action.default is None:
        return "(unset)"
    if _is_flag(action):
        return str(action.default).lower()
    if isinstance(action.default, bool):
        return str(action.default).lower()
    if isinstance(action.default, (int, float)):
        return str(action.default)
    if isinstance(action.default, str) and not action.default:
        return "(empty)"
    return str(action.default)


def _meaning(action: argparse.Action) -> str:
    if isinstance(action, argparse._SubParsersAction):
        names = sorted(action.choices)
        return ("one of: " + ", ".join(f"`{n}`" for n in names)
                + " -- each has its own section below")
    return _collapse(action.help or "")


def _help_of(action: argparse.Action) -> str:
    return _collapse(getattr(action, "help", "") or "")


def _subparser_action(parser: argparse.ArgumentParser
                      ) -> argparse._SubParsersAction | None:
    for act in parser._actions:
        if isinstance(act, argparse._SubParsersAction):
            return act
    return None


def _commands(parser: argparse.ArgumentParser, prefix: str = "",
              help_map: dict[str, str] | None = None
              ) -> list[tuple[str, argparse.ArgumentParser, str, int]]:
    """Every registered command as (path, parser, one-line help, depth),
    parents before their children and sorted by name within each level.

    A subcommand's one-liner lives in its parent's `_choices_actions` (the same
    pseudo-actions `--help` renders), because `add_parser(help=...)` does not put
    it on the child parser."""
    out: list[tuple[str, argparse.ArgumentParser, str, int]] = []
    sub = _subparser_action(parser)
    if sub is None:
        return out
    map_ = help_map if help_map is not None else {
        str(c.dest): _help_of(c) for c in getattr(sub, "_choices_actions", [])
    }
    for name in sorted(sub.choices):
        child = sub.choices[name]
        path = f"{prefix} {name}".strip()
        out.append((path, child, map_.get(name, ""), len(prefix.split()) + 1
                    if prefix else 1))
        out.extend(_commands(child, path))
    return out


def _own_options(parser: argparse.ArgumentParser) -> list[argparse.Action]:
    """A parser's real options minus `-h`, in declaration order. Inherited
    (`parents=[...]`) options are returned too -- every command section lists
    everything it accepts -- while `_shared_actions` counts the ones declared
    once and handed to several commands, so the document can name those parents
    on their own."""
    return [a for a in parser._actions
            if a.option_strings and a.option_strings[0] != "-h"]


def _shared_actions(commands: list[tuple[str, argparse.ArgumentParser, str, int]]
                    ) -> dict[argparse.Action, set[str]]:
    """Actions that appear in more than one parser in the tree. argparse
    copies a `parents=[...]` action object into each child rather than cloning
    it, so object identity -- not option spelling -- is what separates a shared
    parent option from two commands that independently declare the same flag."""
    seen: dict[argparse.Action, set[str]] = {}
    for path, parser, _help, _depth in commands:
        for action in parser._actions:
            if action.option_strings and action.option_strings[0] != "-h":
                seen.setdefault(action, set()).add(path)
    return {action: paths for action, paths in seen.items() if len(paths) > 1}


def _usage_line(parser: argparse.ArgumentParser) -> str:
    """argparse's own usage line, re-flowed to one logical string.

    `_format_usage` only ever breaks *between* argument groups, so collapsing
    the whitespace it inserted yields the same text at every terminal width."""
    text = _collapse(parser.format_usage())
    text = re.sub(r"^usage:\s*", "", text)
    text = text.replace(" [-h]", "", 1)
    return text


def _group_note(parser: argparse.ArgumentParser) -> list[str]:
    """The mutually exclusive groups argparse enforces, which no single option
    row can express: `translate` requires one of `--chapters` / `--next`, while
    `logs` merely permits one of `--io` / `--no-io`."""
    notes: list[str] = []
    for group in parser._mutually_exclusive_groups:
        flags = [a.option_strings[0] for a in group._group_actions
                 if a.option_strings]
        if not flags:
            continue
        lead = "Exactly one of" if group.required else "At most one of"
        notes.append(f"{lead}: " + ", ".join(f"`{f}`" for f in flags) + ".")
    return notes


def _command_section(path: str, parser: argparse.ArgumentParser, one_liner: str
                     ) -> list[str]:
    lines = [f"### `{path}`", ""]
    if one_liner:
        lines += _paragraph(one_liner) + [""]
    lines += _wrap(_usage_line(parser), USAGE_WIDTH, "    ", "        ") + [""]
    for note in _group_note(parser):
        lines += _paragraph(note) + [""]
    rows = []
    for action in _own_options(parser):
        required = action.required or any(
            action in g._group_actions and g.required
            for g in parser._mutually_exclusive_groups)
        meaning = _meaning(action)
        if required:
            meaning = (meaning + " (required)").strip()
        rows.append(f"| `{_cell(_label(action))}` | {_default(action)} | "
                    f"{_cell(meaning)} |")
    positionals = [a for a in parser._actions if not a.option_strings
                   and a.dest != "help"]
    for action in positionals:
        meaning = _meaning(action)
        if action.required and not isinstance(action,
                                              argparse._SubParsersAction):
            meaning = (meaning + " (required)").strip()
        rows.append(f"| `{_cell(_label(action))}` | {_default(action)} | "
                    f"{_cell(meaning)} |")
    if rows:
        lines.append("| argument | default | meaning |")
        lines.append("|---|---|---|")
        lines.extend(rows)
        lines.append("")
    return lines


def _sentence(text: str) -> str:
    """Collapse a help string and end it with a full stop, so it can be joined
    to a following clause."""
    body = _collapse(text)
    if not body:
        return ""
    return body if body.endswith((".", "!", "?")) else body + "."


def _shared_section(commands: list[tuple[str, argparse.ArgumentParser, str, int]],
                    shared: dict[argparse.Action, set[str]]) -> list[str]:
    if not shared:
        return []
    top_level = {path for path, _p, _h, d in commands if d == 1}
    lines = ["## Shared options", ""]
    lines += _paragraph(
        "argparse `parents=[...]` copies one action object into every child that "
        "lists it, so these are declared once in `translate.py` and accepted "
        "widely. The same option spelling declared independently by two "
        "commands is *not* shared -- it is two options, and each is documented "
        "in its own section above.")
    lines.append("")
    for action in sorted(shared, key=lambda a: (a.option_strings or [a.dest])[0]):
        paths = sorted(shared[action])
        accepts = ("every command" if set(paths) >= top_level
                   else ", ".join(f"`{p}`" for p in paths))
        label = ", ".join(f"`{o}`" for o in action.option_strings)
        sentence = (f"- **{label}** ({_placeholder(action) or 'flag'}) -- "
                    f"{_sentence(_help_of(action))} Accepted by {accepts}.")
        lines += _wrap(sentence, PROSE_WIDTH, "", "  ")
    lines.append("")
    return lines


def _exit_section() -> list[str]:
    lines = ["## Exit codes", ""]
    lines += _paragraph(
        "The one table here that argparse cannot supply. "
        "`references/file-formats.md` section \"Exit codes\" remains normative "
        "and lists every command that can exit 1 and why; this is the shared "
        "contract.")
    lines += ["", "| exit | meaning | applies to |", "|---|---|---|"]
    for code, meaning, applies in EXIT_CODES:
        lines.append(f"| {code} | {_cell(meaning)} | {applies} |")
    lines.append("")
    return lines


def build() -> str:
    """The whole document, as text. Pure: reads the parser, writes nothing."""
    root = translate._build_parser()
    commands = _commands(root)
    shared = _shared_actions(commands)

    lines: list[str] = [_HEADER.rstrip("\n"), _INVOCATION.rstrip("\n"),
                     "## Commands", ""]
    lines.append("| command | what it does |")
    lines.append("|---|---|")
    for path, _parser, one_liner, _depth in commands:
        lines.append(f"| `{path}` | {_cell(one_liner)} |")
    lines.append("")
    lines += ["", "## Detail", ""]
    lines += _paragraph(
        "One section per command: its usage line, the mutually exclusive groups "
        "argparse enforces, and every argument it accepts with its default.")
    lines.append("")
    for path, parser, one_liner, _depth in commands:
        lines += _command_section(path, parser, one_liner)
    lines += _shared_section(commands, shared)
    lines += _exit_section()
    return "\n".join(lines).rstrip("\n") + "\n"


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(
        prog="gen_cli_doc.py",
        description="Regenerate references/cli.md from translate.py's argparse "
                    "tree.")
    parser.add_argument("--check", action="store_true",
                        help="report whether the committed file is stale; write "
                             "nothing")
    args = parser.parse_args(argv)

    wanted = build().encode("utf-8")
    current = DOC_PATH.read_bytes() if DOC_PATH.is_file() else None

    if args.check:
        if current == wanted:
            print(f"[ok] {DOC_PATH.name} matches the parser")
            return 0
        print(f"[FAIL] {DOC_PATH} is stale - run "
              f"'uv run scripts/gen_cli_doc.py' and commit the result")
        if current is not None:
            print(f"       committed {len(current)} bytes, "
                  f"parser describes {len(wanted)}")
        return 1

    DOC_PATH.parent.mkdir(parents=True, exist_ok=True)
    with open(DOC_PATH, "wb") as fh:
        fh.write(wanted)
    verb = "unchanged" if current == wanted else "written"
    print(f"[ok] {DOC_PATH} {verb} ({len(wanted)} bytes)")
    return 0


if __name__ == "__main__":
    sys.exit(main())